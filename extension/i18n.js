// "auto" follows the browser languages (pt -> pt-BR, zh -> zh-CN), English if nothing matches
function resolveLang(lang) {
  if (lang && lang !== 'auto') return I18N[lang] ? lang : 'en';
  let prefs = [];
  try {
    prefs = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language]).filter(Boolean);
  } catch (_) {}
  const codes = Object.keys(LANGS);
  for (const p of prefs) {
    const lc = String(p).toLowerCase();
    const exact = codes.find((c) => c.toLowerCase() === lc);
    if (exact) return exact;
    const base = lc.split('-')[0];
    const byBase = codes.find((c) => c.toLowerCase() === base) || codes.find((c) => c.toLowerCase().split('-')[0] === base);
    if (byBase) return byBase;
  }
  return 'en';
}

function t(lang, key, vars) {
  lang = resolveLang(lang);
  const s = (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars && k in vars ? vars[k] : ''));
}
